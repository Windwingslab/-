    function curve(fn, x0, y0, x1, y1, n) {
        var pts = ["l"];
        for (var i = 0; i <= n; i++) {
            var t = i / n;
            pts.push(x0 + (x1 - x0) * t, y0 + (y1 - y0) * fn(t));
        }
        return pts;
    }
    function arc(cx, cy, r, a0, a1, n) {
        var pts = ["l"];
        for (var i = 0; i <= n; i++) {
            var a = (a0 + (a1 - a0) * i / n) * Math.PI / 180;
            pts.push(cx + r * Math.cos(a), cy + r * Math.sin(a));
        }
        return pts;
    }
    function key(x, y, r) { r = r || 2; return ["p", x, y - r, x + r, y, x, y + r, x - r, y]; }

